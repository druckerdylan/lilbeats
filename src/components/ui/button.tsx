function Button({
  className,
  variant = "default",
  size = "default",
  nativeButton,
  render,
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      // Base UI assumes a real <button> unless told otherwise, and warns when
      // `render` swaps in something else. Almost every `render` here is a
      // next/link anchor, so default to false and let callers override.
      nativeButton={nativeButton ?? (render === undefined)}
      render={render}
      {...props}
    />
  )
}

export { Button, buttonVariants }
